#include <stdio.h>
#include <string.h>

int main() {
    char str[100];
    printf("Enter string for grammar (a*b*): ");
    scanf("%s", str);
    
    int i = 0;
    while(str[i] == 'a') i++;
    while(str[i] == 'b') i++;
    
    if (i == strlen(str)) {
        printf("String is generated by the grammar\n");
    } else {
        printf("String is NOT generated by the grammar\n");
    }
    return 0;
}